"""Historical Native v6 offline falsification of signed shared support.

This script does not modify Taiji runtime state, topology or checkpoints.  It
listens to the real decoder-0 local writes made by M6 consolidation and mirrors
them into experimental banks with two changes only:

1. each cortical trace is represented as ON/OFF opponent activity around a
   waking-stream baseline, yielding a signed residual; and
2. every cortical coordinate has one fixed fan-out into a shared receptor bank,
   while every outcome row reads all bank channels.

The target is still generated by ``EpisodicField.replay``.  There is no event
list, teacher label, backward pass or write into the production substrate.
"""

